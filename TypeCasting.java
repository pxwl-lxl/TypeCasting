public class TypeCasting {
	public static void main(String[] args) {

	// Type Casting - Changing one data type into another.
	
	// dataType double to int	

	double price1 = 20.50;

	int newPrice1 = (int) price1;

	System.out.println(newPrice1);

	// dataType int to double
	
	int price2 = 22;

	double newPrice2 = (double) price2;

	System.out.println(newPrice2);

	}
}